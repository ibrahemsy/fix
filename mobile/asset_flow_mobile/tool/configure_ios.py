from pathlib import Path
import re

podfile = Path("ios/Podfile")
if not podfile.exists():
    raise SystemExit("ios/Podfile was not generated by Flutter; run flutter pub get first.")

content = podfile.read_text()
if re.search(r"^\s*#\s*platform :ios", content, flags=re.MULTILINE):
    content = re.sub(
        r"^\s*#\s*platform :ios.*$",
        "platform :ios, '15.5'",
        content,
        count=1,
        flags=re.MULTILINE,
    )
elif re.search(r"^platform :ios", content, flags=re.MULTILINE):
    content = re.sub(
        r"^platform :ios.*$",
        "platform :ios, '15.5'",
        content,
        count=1,
        flags=re.MULTILINE,
    )
else:
    content = "platform :ios, '15.5'\n" + content
podfile.write_text(content)

project = Path("ios/Runner.xcodeproj/project.pbxproj")
if project.exists():
    project_content = project.read_text()
    project_content = re.sub(
        r"IPHONEOS_DEPLOYMENT_TARGET = [0-9.]+;",
        "IPHONEOS_DEPLOYMENT_TARGET = 15.5;",
        project_content,
    )
    project.write_text(project_content)
